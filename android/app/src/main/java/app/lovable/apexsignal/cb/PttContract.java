package app.lovable.apexsignal.cb;

import android.view.KeyEvent;

/**
 * The PTT key contract: every broadcast action and key code the container
 * listens for, with its evidence class printed next to it.
 *
 * VERIFIED actions come from public documentation (cited in the PR):
 *   - com.zello.ptt.down / .up and com.zello.intent.buttonExtra1.down / .up
 *     Zello's official hardware-partner integration guide. Rugged-handset
 *     firmware (Ulefone's custom key defaults to "Zello (PTT)" in Ulefone's
 *     own product copy) is built to emit these for the bound PTT app.
 *   - android.intent.action.PTT.down / .up
 *     The generic PTT intent convention: generated by Fast Talkie, and
 *     documented with KEYCODE_F11 in the UNIWA F41 intercom manual.
 *   - com.sonim.intent.action.PTT_KEY_DOWN / PTT_KEY_UP
 *     Sonim's documented programmable-key intents.
 *
 * UNVERIFIED actions were already present in the estate's tinyradr code and
 * are kept as best-effort receiver filters only. No public source documents
 * them; a filter that never matches costs nothing, but nothing in this build
 * depends on them firing.
 */
final class PttContract {
    private PttContract() {}

    static final String[] DOWN_ACTIONS = {
        "com.zello.ptt.down",                    // VERIFIED (Zello)
        "com.zello.intent.buttonExtra1.down",    // VERIFIED (Zello extra button)
        "android.intent.action.PTT.down",        // VERIFIED (generic convention)
        "com.sonim.intent.action.PTT_KEY_DOWN",  // VERIFIED (Sonim)
        // UNVERIFIED — best effort only:
        "android.intent.action.PTT_DOWN",
        "com.android.action.PTT.down",
        "com.ulefone.ptt.down",
        "android.intent.action.SIDE_KEY_DOWN",
    };

    static final String[] UP_ACTIONS = {
        "com.zello.ptt.up",                      // VERIFIED (Zello)
        "com.zello.intent.buttonExtra1.up",      // VERIFIED (Zello extra button)
        "android.intent.action.PTT.up",          // VERIFIED (generic convention)
        "com.sonim.intent.action.PTT_KEY_UP",    // VERIFIED (Sonim)
        // UNVERIFIED — best effort only:
        "android.intent.action.PTT_UP",
        "com.android.action.PTT.up",
        "com.ulefone.ptt.up",
        "android.intent.action.SIDE_KEY_UP",
    };

    /** Key codes rugged side keys commonly deliver to a foreground activity. */
    static final int[] KNOWN_KEYCODES = {
        KeyEvent.KEYCODE_MEDIA_RECORD,   // 130
        KeyEvent.KEYCODE_HEADSETHOOK,    // 79
        KeyEvent.KEYCODE_F11,            // UNIWA-documented PTT key code
        KeyEvent.KEYCODE_F12,
        KeyEvent.KEYCODE_PROG_RED,
        KeyEvent.KEYCODE_BUTTON_1,
        286, 287, 288, 289,              // vendor PTT/SOS codes on several rugged ROMs
    };

    static boolean isDownAction(String a) {
        for (String d : DOWN_ACTIONS) if (d.equals(a)) return true;
        return false;
    }

    static boolean isUpAction(String a) {
        for (String u : UP_ACTIONS) if (u.equals(a)) return true;
        return false;
    }

    static boolean isKnownKeyCode(int code) {
        for (int c : KNOWN_KEYCODES) if (c == code) return true;
        return false;
    }

    /** Gesture timing, shared in spirit with src/lib/ptt-key.ts. */
    static final long LONG_PRESS_MS = 600;   // a hold past this is the long-press gesture
    static final long DOUBLE_TAP_MS = 350;   // second press inside this window is a double
    static final long MAX_KEY_MS = 300_000;  // stuck-key safety release (deck also cuts off)

    static final String ACTION_TALK = "talk";
    static final String ACTION_OPEN = "open";
    static final String ACTION_NONE = "none";
}
